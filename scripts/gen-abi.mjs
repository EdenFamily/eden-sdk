#!/usr/bin/env node
/**
 * Regenerates src/abi/eden.ts from the ABI JSON files in abi/ (copied from the deployed contracts' build output, as
 * served at https://edenfamily.xyz/abi/<file>). The TypeScript copies are `as const` so viem infers argument and
 * event types from them.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const files = readdirSync(`${root}abi`).filter((f) => f.endsWith(".json")).sort();
let out = "/* Generated by scripts/gen-abi.mjs from abi/*.json. Do not edit by hand. */\n";
for (const file of files) {
  const abi = JSON.parse(readFileSync(`${root}abi/${file}`, "utf8"));
  const name = file.replace(/\.json$/, "");
  const ident = name[0].toLowerCase() + name.slice(1) + "Abi";
  out += `\n/** ${name}: full ABI. */\nexport const ${ident} = ${JSON.stringify(abi)} as const;\n`;
}
writeFileSync(`${root}src/abi/eden.ts`, out);
console.log(`wrote src/abi/eden.ts (${files.length} ABIs)`);
